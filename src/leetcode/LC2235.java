public class LC2235 {

    public static int sum(int num1, int num2) {
        return num1 + num2;
    }
    public static void main(String[] args) {
        int num1 = 12;
        int num2 = 5;
        int result = sum(num1, num2);
        System.out.println("Input: num1 = " + num1 + ", num2 = " + num2);
        System.out.println("Output: " + result);
    }
}